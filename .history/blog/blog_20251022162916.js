const totalPages = pageLinks.length;
let currentPage = pageLinks.findIndex(link => window.location.pathname.includes(link)) + 1 || 1;

function createPaginationButtons() {
    paginationContainer.innerHTML = "";

    // Prev Button
    if (currentPage > 1) {
        let prevBtn = document.createElement("button");
        prevBtn.innerHTML = '<i class="fas fa-chevron-left"></i>';
        prevBtn.classList.add("pagination-btn-l4m7");
        prevBtn.onclick = () => {
            window.location.href = pageLinks[currentPage - 2];
        };
        paginationContainer.appendChild(prevBtn);
    }

    function createPageButton(page) {
        let pageBtn = document.createElement("button");
        pageBtn.textContent = page;
        pageBtn.classList.add("pagination-btn-l4m7");
        if (page === currentPage) {
            pageBtn.classList.add("active");
        }
        pageBtn.onclick = () => {
            window.location.href = pageLinks[page - 1];
        };
        paginationContainer.appendChild(pageBtn);
    }

    createPageButton(1); // Always show first page

    if (totalPages <= 7) {
        for (let i = 2; i <= totalPages; i++) {
            createPageButton(i);
        }
    } else {
        const maxVisibleButtons = 5;
        const half = Math.floor(maxVisibleButtons / 2);

        let startPage = Math.max(2, currentPage - half);
        let endPage = Math.min(totalPages - 1, currentPage + half);

        if (currentPage <= half + 1) {
            endPage = maxVisibleButtons;
        } else if (currentPage >= totalPages - half) {
            startPage = totalPages - maxVisibleButtons + 1;
        }

        if (startPage > 2) {
            const dots = document.createElement("span");
            dots.textContent = "...";
            dots.classList.add("pagination-dots");
            paginationContainer.appendChild(dots);
        }

        for (let i = startPage; i <= endPage; i++) {
            createPageButton(i);
        }

        if (endPage < totalPages - 1) {
            const dots = document.createElement("span");
            dots.textContent = "...";
            dots.classList.add("pagination-dots");
            paginationContainer.appendChild(dots);
        }

        createPageButton(totalPages); // Always show last page
    }

    // Next Button
    if (currentPage < totalPages) {
        let nextBtn = document.createElement("button");
        nextBtn.innerHTML = '<i class="fas fa-chevron-right"></i>';
        nextBtn.classList.add("pagination-btn-l4m7");
        nextBtn.onclick = () => {
            window.location.href = pageLinks[currentPage];
        };
        paginationContainer.appendChild(nextBtn);
    }
}

